CREATE TABLE pipeline_version (
  pipeline_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pipeline_id bigint NOT NULL REFERENCES pipeline(pipeline_id),
  version_no int NOT NULL CHECK(version_no>0),
  status varchar(16) NOT NULL DEFAULT 'DRAFT',
  definition jsonb NOT NULL,
  definition_sha256 varchar(64) NOT NULL,
  created_by varchar(64) NOT NULL DEFAULT 'system',
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(pipeline_id,version_no),
  CHECK(status IN('DRAFT','PUBLISHED','ARCHIVED')),
  CHECK(jsonb_typeof(definition)='object'),
  CHECK(jsonb_typeof(definition->'nodeDefinitions')='object'),
  CHECK(jsonb_typeof(definition->'ruleSets')='object'),
  CHECK(definition_sha256~'^[0-9a-f]{64}$')
);
COMMENT ON TABLE pipeline_version IS '不可变流程版本；统一保存 DAG、节点定义、规则、选择、分配、重试、跨日和节点凭据。';
COMMENT ON COLUMN pipeline_version.pipeline_version_id IS 'PipelineVersion ID，bigint 身份主键。';
COMMENT ON COLUMN pipeline_version.pipeline_id IS '所属 pipeline 外键。';
COMMENT ON COLUMN pipeline_version.version_no IS 'Pipeline 内正整数版本号。';
COMMENT ON COLUMN pipeline_version.status IS 'DRAFT/PUBLISHED/ARCHIVED；仅 PUBLISHED 可提交。';
COMMENT ON COLUMN pipeline_version.definition IS '统一配置 JSONB；nodeDefinitions/ruleSets/nodes/config，普通 API 必须脱敏。';
COMMENT ON COLUMN pipeline_version.definition_sha256 IS 'definition 的 64 位小写 SHA-256。';
COMMENT ON COLUMN pipeline_version.created_by IS '版本创建操作者。';
