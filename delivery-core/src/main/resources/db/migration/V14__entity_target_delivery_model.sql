CREATE OR REPLACE FUNCTION archive_delivery.validate_source_artifacts() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE artifact jsonb; mapping text;
BEGIN
  IF jsonb_typeof(NEW.artifacts)<>'array' THEN RAISE EXCEPTION 'artifacts must be an array'; END IF;
  FOR artifact IN SELECT value FROM jsonb_array_elements(NEW.artifacts)
  LOOP
    IF jsonb_typeof(artifact)<>'object' OR NOT(artifact ?& ARRAY['artifactSeq','originalFileName','newFileName','sizeBytes','sha256','token','file_mapping'])
       OR EXISTS(SELECT 1 FROM jsonb_object_keys(artifact) k WHERE k NOT IN
         ('artifactSeq','originalFileName','newFileName','sizeBytes','sha256','token','file_mapping')) THEN
      RAISE EXCEPTION 'artifact must contain exactly the seven contracted fields';
    END IF;
    IF (artifact->>'artifactSeq')::int<=0 OR (artifact->>'sizeBytes')::bigint<0 OR (artifact->>'token')::bigint<0
       OR artifact->>'sha256'!~'^[0-9a-f]{64}$' OR jsonb_typeof(artifact->'file_mapping')<>'object'
       OR artifact->>'originalFileName' LIKE '%/%' OR artifact->>'originalFileName' LIKE '%..%'
       OR artifact->>'newFileName' LIKE '%/%' OR artifact->>'newFileName' LIKE '%..%' THEN
      RAISE EXCEPTION 'artifact values violate the source_data contract';
    END IF;
    FOR mapping IN SELECT value::text FROM jsonb_each(artifact->'file_mapping')
    LOOP
      IF mapping IS NULL OR mapping='' THEN RAISE EXCEPTION 'file_mapping values must be non-empty'; END IF;
    END LOOP;
  END LOOP;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.artifacts) a GROUP BY a.value->>'artifactSeq' HAVING count(*)>1)
     OR EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.artifacts) a GROUP BY a.value->>'newFileName' HAVING count(*)>1) THEN
    RAISE EXCEPTION 'artifactSeq and newFileName must be unique within artifacts';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_source_artifacts BEFORE INSERT OR UPDATE ON source_data
  FOR EACH ROW EXECUTE FUNCTION archive_delivery.validate_source_artifacts();
COMMENT ON FUNCTION archive_delivery.validate_source_artifacts() IS '强制 artifacts 七字段白名单、安全文件名、非负数值、SHA 和数组内唯一性。';

