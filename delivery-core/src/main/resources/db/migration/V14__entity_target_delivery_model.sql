  CHECK(jsonb_typeof(target_strategy->'targets')='array'),
  CHECK(status IN('SUBMITTED','DISCOVERING','PLANNING','PROCESSING','WAITING','RETRYING','BLOCKED','DELIVERED','COMPLETED_WITH_CANCELLATIONS','CANCELLED'))
);
CREATE INDEX idx_submit_status ON delivery_submit(status,updated_at,delivery_id);
CREATE INDEX idx_submit_pipeline ON delivery_submit(pipeline_version_id,delivery_id);
