CREATE TABLE source_data (
  data_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id bigint NOT NULL REFERENCES delivery_submit(delivery_id),
  original_request_id varchar(256),
  new_request_id varchar(256),
  request_namespace varchar(128) NOT NULL DEFAULT '',
  original_locator jsonb NOT NULL DEFAULT '{}',
  output_locator jsonb NOT NULL DEFAULT '{}',
  qualification varchar(32) NOT NULL DEFAULT 'PENDING',
  filter_rule_code varchar(128),
  filter_reason varchar(1024),
  affected_count bigint NOT NULL DEFAULT 0 CHECK(affected_count>=0),
  rule_version varchar(128),
  size_bytes bigint NOT NULL DEFAULT 0 CHECK(size_bytes>=0),
  token_count bigint NOT NULL DEFAULT 0 CHECK(token_count>=0),
  sha256 varchar(64),
  artifacts jsonb NOT NULL DEFAULT '[]',
  CHECK(jsonb_typeof(original_locator)='object' AND jsonb_typeof(output_locator)='object' AND jsonb_typeof(artifacts)='array'),
  CHECK(qualification IN('PENDING','QUALIFIED','QUALIFIED_WITH_SKIPS','FILTERED','UNQUALIFIED')),
  CHECK(qualification<>'FILTERED' OR(filter_rule_code IS NOT NULL AND filter_reason IS NOT NULL)),
  CHECK(sha256 IS NULL OR sha256~'^[0-9a-f]{64}$')
);
CREATE UNIQUE INDEX uk_source_request_id ON source_data(request_namespace,new_request_id)
  WHERE new_request_id IS NOT NULL AND qualification<>'FILTERED';
CREATE UNIQUE INDEX uk_source_asset ON source_data(delivery_id,(original_locator->>'sourceUri'),(original_locator->>'sourceVersion'))
  WHERE qualification<>'FILTERED';
CREATE INDEX idx_source_delivery_qualification ON source_data(delivery_id,qualification,data_id);
CREATE INDEX idx_source_delivery_sha ON source_data(delivery_id,sha256) WHERE sha256 IS NOT NULL;
COMMENT ON TABLE source_data IS '提交内源数据事实；保存定位、过滤、请求映射和严格七字段 artifacts。';
COMMENT ON COLUMN source_data.data_id IS '源数据 ID，供 delivery_task 引用。';
COMMENT ON COLUMN source_data.delivery_id IS '所属 delivery_submit 外键。';
COMMENT ON COLUMN source_data.original_request_id IS '原始请求编号，包级或未知时可空。';
COMMENT ON COLUMN source_data.new_request_id IS 'repair 后请求编号，未编号或过滤时可空。';
COMMENT ON COLUMN source_data.request_namespace IS '请求编号命名空间。';
COMMENT ON COLUMN source_data.original_locator IS 'sourceUri/sourceVersion/memberPath/responsePaths JSONB。';
COMMENT ON COLUMN source_data.output_locator IS 'repair 后 memberPath/manifestPath JSONB，不保存交付 URI。';
COMMENT ON COLUMN source_data.qualification IS 'PENDING/QUALIFIED/QUALIFIED_WITH_SKIPS/FILTERED/UNQUALIFIED。';
COMMENT ON COLUMN source_data.filter_rule_code IS '过滤规则机器码，FILTERED 必填。';
COMMENT ON COLUMN source_data.filter_reason IS '脱敏过滤原因，FILTERED 必填。';
