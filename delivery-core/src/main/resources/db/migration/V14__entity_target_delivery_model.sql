CREATE TABLE delivery_node (
  process_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id bigint NOT NULL REFERENCES delivery_submit(delivery_id),
  task_id bigint NOT NULL REFERENCES delivery_task(task_id),
  original_file_name varchar(512) NOT NULL,
  new_file_name varchar(512) NOT NULL,
  node_id varchar(64) NOT NULL,
  node_type varchar(128) NOT NULL,
  stage_code varchar(64) NOT NULL,
  attempt int NOT NULL CHECK(attempt>0),
  fence bigint NOT NULL,
  status varchar(16) NOT NULL,
