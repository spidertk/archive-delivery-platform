CREATE TABLE delivery_submit (
  delivery_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_batch varchar(128) NOT NULL,
  source_id bigint NOT NULL REFERENCES ingest_source(source_id),
  pipeline_version_id bigint NOT NULL REFERENCES pipeline_version(pipeline_version_id),
  idempotency_key varchar(128) NOT NULL UNIQUE,
  delivery_date date NOT NULL,
  cutoff_at timestamptz NOT NULL,
  submitted_at timestamptz NOT NULL DEFAULT now(),
