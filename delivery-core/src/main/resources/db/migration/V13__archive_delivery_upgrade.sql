COMMENT ON COLUMN source_pipeline_binding.pipeline_version_id IS 'pipeline_version 外键，非空。';
COMMENT ON COLUMN source_pipeline_binding.effective_from IS '绑定生效时间，timestamptz。';
COMMENT ON COLUMN source_pipeline_binding.effective_to IS '绑定失效时间；当前绑定可空。';
