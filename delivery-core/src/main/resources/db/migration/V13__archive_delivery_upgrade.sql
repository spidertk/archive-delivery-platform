COMMENT ON COLUMN ingest_source.oss_uri IS '非空唯一 OSS 来源 URI；不含 AK/SK、签名参数。';
COMMENT ON COLUMN ingest_source.availability_status IS 'AVAILABLE 可用于新提交，UNAVAILABLE 不可用于新提交。';
COMMENT ON COLUMN ingest_source.channel_code IS '非空数据供应商或业务渠道编码。';
COMMENT ON COLUMN ingest_source.oss_type IS '非空对象存储厂商类型，例如 ALIBABA_CLOUD。';
COMMENT ON COLUMN ingest_source.previous_refresh_bytes IS '上一次成功刷新总字节数，非负。';
COMMENT ON COLUMN ingest_source.latest_refresh_bytes IS '最近一次成功刷新总字节数，非负。';

