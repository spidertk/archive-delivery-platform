COMMENT ON COLUMN delivery_entity.entity_code IS '厂商内交付实体编码，非空。';
COMMENT ON COLUMN delivery_entity.entity_name IS '管理展示名称，非空。';
COMMENT ON COLUMN delivery_entity.protocol IS '实体交付能力协议；核心验证为 FTP，不决定 Pipeline 顺序。';
COMMENT ON COLUMN delivery_entity.account_name IS '交付业务账户名，不是密码。';
COMMENT ON COLUMN delivery_entity.endpoint_locator IS 'JSONB 对象；schemaVersion/host/port/rootPath 白名单定位，不含 Secret。';
COMMENT ON COLUMN delivery_entity.enabled IS '是否允许绑定新提交；false 不删除历史关系。';
COMMENT ON COLUMN delivery_entity.created_at IS '实体创建时间，timestamptz。';
COMMENT ON COLUMN delivery_entity.updated_at IS '实体最近修改时间，timestamptz。';

