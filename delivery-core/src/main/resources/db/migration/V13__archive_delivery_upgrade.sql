CREATE TABLE delivery_task (
  task_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  delivery_id bigint NOT NULL REFERENCES delivery_pipeline_submit(delivery_id),
  data_id bigint NOT NULL REFERENCES source_data(data_id),
  delivery_group_id bigint NOT NULL REFERENCES delivery_group(group_id),
  artifact_seq int NOT NULL CHECK(artifact_seq>0),
  delivery_date date NOT NULL,
  cutoff_at timestamptz NOT NULL,
  original_file_name varchar(512) NOT NULL,
  new_file_name varchar(512) NOT NULL,
  size_bytes bigint NOT NULL DEFAULT 0 CHECK(size_bytes>=0),
  token_count bigint NOT NULL DEFAULT 0 CHECK(token_count>=0),
  sha256 varchar(64),
  current_node_id varchar(64) NOT NULL,
  execution_status varchar(24) NOT NULL DEFAULT 'READY',
  lease_owner varchar(128),
  lease_until timestamptz,
  fence bigint NOT NULL DEFAULT 0,
  retry_count int NOT NULL DEFAULT 0 CHECK(retry_count>=0),
  next_retry_at timestamptz,
  last_error_code varchar(128),
  superseded_by_task_id bigint REFERENCES delivery_task(task_id),
  invalidated_at timestamptz,
  invalidation_reason varchar(128),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(delivery_group_id,delivery_date,new_file_name),UNIQUE(superseded_by_task_id),
  CHECK(sha256 IS NULL OR sha256~'^[0-9a-f]{64}$'),
  CHECK(execution_status IN('READY','RUNNING','WAITING','RETRY_WAIT','BLOCKED','SUCCEEDED','EXPIRED','CANCELLED')),
  CHECK((execution_status='EXPIRED')=(invalidated_at IS NOT NULL)),
  CHECK(superseded_by_task_id IS NULL OR superseded_by_task_id<>task_id)
);
CREATE UNIQUE INDEX uk_task_active_artifact ON delivery_task(delivery_group_id,data_id,artifact_seq)
  WHERE execution_status NOT IN('EXPIRED','CANCELLED');
CREATE INDEX idx_task_delivery ON delivery_task(delivery_id,execution_status,delivery_date,task_id);
