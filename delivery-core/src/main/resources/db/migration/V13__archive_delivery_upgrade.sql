CREATE TABLE ingest_source (
  source_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  oss_uri varchar(1280) NOT NULL UNIQUE,
  availability_status varchar(16) NOT NULL DEFAULT 'AVAILABLE',
  channel_code varchar(64) NOT NULL,
  oss_type varchar(32) NOT NULL,
  previous_refresh_bytes bigint NOT NULL DEFAULT 0 CHECK(previous_refresh_bytes>=0),
  latest_refresh_bytes bigint NOT NULL DEFAULT 0 CHECK(latest_refresh_bytes>=0),
  CHECK(availability_status IN('AVAILABLE','UNAVAILABLE')),
  CHECK(oss_uri LIKE 'oss://%' AND oss_uri NOT LIKE '%?%')
);
COMMENT ON TABLE ingest_source IS '对象存储来源登记；只保存无密钥 OSS URI、可用状态、渠道、OSS 类型和最近两次成功刷新字节数。';
