CREATE SCHEMA IF NOT EXISTS archive_delivery;
SET search_path TO archive_delivery;

CREATE TABLE production_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_code varchar(32) NOT NULL UNIQUE,
    provider_code varchar(32) NOT NULL UNIQUE,
    compute_host varchar(128) NOT NULL,
    ftp_host varchar(128) NOT NULL,
    target_root varchar(256) NOT NULL,
    business_timezone varchar(64) NOT NULL DEFAULT 'Asia/Shanghai',
    delivery_cutoff_time time NOT NULL DEFAULT '02:00',
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE production_group (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_line_id bigint NOT NULL REFERENCES production_line(id),
    archive_date date NOT NULL,
    group_no integer NOT NULL,
    target_count integer NOT NULL CHECK (target_count > 0),
    assigned_count integer NOT NULL DEFAULT 0 CHECK (assigned_count >= 0),
    status varchar(16) NOT NULL DEFAULT 'FILLING',
    sealed_at timestamptz,
    UNIQUE (production_line_id, archive_date, group_no),
    CHECK (assigned_count <= target_count)
);

CREATE TABLE pipeline (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_code varchar(64) NOT NULL UNIQUE,
    description varchar(512) NOT NULL DEFAULT ''
);

CREATE TABLE pipeline_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id bigint NOT NULL REFERENCES pipeline(id),
    version_no integer NOT NULL,
    status varchar(16) NOT NULL,
    definition jsonb NOT NULL,
    definition_sha256 char(64) NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (pipeline_id, version_no)
);

CREATE TABLE ingest_source (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code varchar(64) NOT NULL UNIQUE,
    source_type varchar(16) NOT NULL,
    bucket_ref varchar(128) NOT NULL,
    object_prefix varchar(512) NOT NULL,
    discovery_cursor jsonb NOT NULL DEFAULT '{}',
    priority integer NOT NULL DEFAULT 100,
    enabled boolean NOT NULL DEFAULT true
);

CREATE TABLE source_pipeline_binding (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES ingest_source(id),
    pipeline_version_id bigint NOT NULL REFERENCES pipeline_version(id),
    effective_from timestamptz NOT NULL DEFAULT now(),
    effective_to timestamptz
);
CREATE UNIQUE INDEX uk_source_active_binding ON source_pipeline_binding(source_id) WHERE effective_to IS NULL;

CREATE TABLE source_package (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES ingest_source(id),
    pipeline_version_id bigint NOT NULL REFERENCES pipeline_version(id),
    definition_snapshot jsonb NOT NULL,
    bucket_name varchar(128) NOT NULL,
    object_key varchar(1024) NOT NULL,
    object_version varchar(256) NOT NULL,
    object_etag varchar(256),
    source_sha256 char(64),
    source_size bigint NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'DISCOVERED',
    run_status varchar(16) NOT NULL DEFAULT 'READY',
    production_line_id bigint REFERENCES production_line(id),
    process_date date,
    planned_at timestamptz,
    discovered_at timestamptz NOT NULL DEFAULT now(),
    current_node varchar(64) NOT NULL DEFAULT 'download',
    lease_owner varchar(128),
    lease_until timestamptz,
    fence bigint NOT NULL DEFAULT 0,
    retry_count integer NOT NULL DEFAULT 0,
    next_retry_at timestamptz,
    last_error_code varchar(128),
    manifest jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (bucket_name, object_key, object_version)
);
CREATE INDEX idx_source_claim ON source_package(production_line_id, run_status, next_retry_at, id);

CREATE TABLE source_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_package_id bigint NOT NULL REFERENCES source_package(id),
    member_key varchar(256) NOT NULL,
    original_path varchar(1024) NOT NULL,
    original_request_id varchar(256),
    qualification varchar(32) NOT NULL DEFAULT 'PENDING',
    filter_rule_code varchar(128),
    filter_reason varchar(1024),
    rule_version varchar(128),
    repaired_manifest jsonb,
    UNIQUE (source_package_id, member_key)
);

CREATE TABLE output_package (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_package_id bigint NOT NULL REFERENCES source_package(id),
    pipeline_version_id bigint NOT NULL REFERENCES pipeline_version(id),
    production_group_id bigint NOT NULL REFERENCES production_group(id),
    production_line_id bigint NOT NULL REFERENCES production_line(id),
    archive_date date NOT NULL,
    delivery_date date NOT NULL,
    cutoff_at timestamptz NOT NULL,
    rollover_count integer NOT NULL DEFAULT 0,
    last_rollover_at timestamptz,
    group_seq integer NOT NULL,
    new_package_name varchar(512) NOT NULL,
    status varchar(24) NOT NULL DEFAULT 'GROUPED',
    run_status varchar(16) NOT NULL DEFAULT 'READY',
    current_node varchar(64) NOT NULL DEFAULT 'hzUpload',
    lease_owner varchar(128),
    lease_until timestamptz,
    fence bigint NOT NULL DEFAULT 0,
    retry_count integer NOT NULL DEFAULT 0,
    next_retry_at timestamptz,
    last_error_code varchar(128),
    manifest jsonb NOT NULL,
    hz_path varchar(1024),
    sg_source_path varchar(1024),
    sg_download_path varchar(1024),
    published_path varchar(1024),
    receipt_id varchar(256),
    delivered_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_package_id, new_package_name),
    UNIQUE (production_group_id, group_seq),
    UNIQUE (production_line_id, archive_date, new_package_name)
);
CREATE INDEX idx_output_claim ON output_package(production_line_id, run_status, next_retry_at, id);
CREATE INDEX idx_output_rollover ON output_package(production_line_id, cutoff_at, id) WHERE status <> 'DELIVERED';

CREATE TABLE number_counter (
    namespace varchar(128) PRIMARY KEY,
    next_value bigint NOT NULL CHECK (next_value >= 0)
);

CREATE TABLE number_reservation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace varchar(128) NOT NULL,
    source_package_id bigint NOT NULL REFERENCES source_package(id),
    request_key varchar(256) NOT NULL,
    start_value bigint NOT NULL,
    count_value integer NOT NULL CHECK (count_value > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (namespace, source_package_id, request_key),
    UNIQUE (namespace, start_value)
);

CREATE TABLE request_mapping (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_member_id bigint NOT NULL REFERENCES source_member(id),
    output_package_id bigint REFERENCES output_package(id),
    original_request_id varchar(256),
    new_request_id varchar(256),
    reservation_id bigint REFERENCES number_reservation(id),
    mapping_rule_version varchar(128) NOT NULL,
    discovered_at timestamptz NOT NULL DEFAULT now(),
    grouped_at timestamptz,
    UNIQUE (source_member_id),
    UNIQUE (new_request_id)
);
CREATE INDEX idx_mapping_output ON request_mapping(output_package_id);

CREATE TABLE output_artifact (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    output_package_id bigint NOT NULL REFERENCES output_package(id),
    artifact_seq integer NOT NULL,
    original_file_name varchar(1024),
    new_file_name varchar(1024) NOT NULL,
    size_bytes bigint NOT NULL,
    sha256 char(64) NOT NULL,
    hz_path varchar(1024),
    sg_path varchar(1024),
    published_path varchar(1024),
    metadata jsonb NOT NULL DEFAULT '{}',
    UNIQUE (output_package_id, artifact_seq),
    UNIQUE (output_package_id, new_file_name)
);

CREATE TABLE package_node_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_package_id bigint REFERENCES source_package(id),
    output_package_id bigint REFERENCES output_package(id),
    node_id varchar(64) NOT NULL,
    node_type varchar(128) NOT NULL,
    implementation varchar(128) NOT NULL,
    attempt integer NOT NULL,
    fence bigint NOT NULL,
    status varchar(16) NOT NULL,
    worker_instance_id varchar(128) NOT NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    input_manifest jsonb,
    output_manifest jsonb,
    error_code varchar(128),
    error_detail text,
    CHECK ((source_package_id IS NULL) <> (output_package_id IS NULL))
);
CREATE UNIQUE INDEX uk_source_node_attempt ON package_node_run(source_package_id, node_id, attempt) WHERE source_package_id IS NOT NULL;
CREATE UNIQUE INDEX uk_output_node_attempt ON package_node_run(output_package_id, node_id, attempt) WHERE output_package_id IS NOT NULL;

CREATE TABLE package_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id bigint NOT NULL REFERENCES package_node_run(id),
    event_seq bigint NOT NULL,
    event_type varchar(64) NOT NULL,
    event_time timestamptz NOT NULL DEFAULT now(),
    message varchar(1024),
    payload jsonb NOT NULL DEFAULT '{}',
    UNIQUE (run_id, event_seq)
);
