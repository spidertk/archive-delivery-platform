  CHECK(jsonb_typeof(definition)='object'),
  CHECK(jsonb_typeof(definition->'nodeDefinitions')='object'),
  CHECK(jsonb_typeof(definition->'ruleSets')='object'),
  CHECK(definition_sha256~'^[0-9a-f]{64}$')
);
